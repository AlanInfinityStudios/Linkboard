    cands=[set(g[1])|set(g[2]) for g in gs]
    sols=[]
    def rec(i, used, pick):
        if i==4: sols.append(pick); return
        for c in combinations(sorted(cands[i]-used),4): rec(i+1, used|set(c), pick+[c])
    rec(0,set(),[])
    print(name, "solutions:", len(sols))
